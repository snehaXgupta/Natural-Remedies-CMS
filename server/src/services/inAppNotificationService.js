import { InAppNotification, Complaint, ComplaintAssignment, User } from '../models/index.js';

export async function createNotification({ recipient, complaint, title, message, link }) {
  if (!recipient) return null;

  // 1. Deduplication guard: do not create duplicate notification for the same recipient
  // with identical complaint and title within 5 minutes.
  const windowTime = new Date(Date.now() - 5 * 60 * 1000);
  try {
    const existing = await InAppNotification.findOne({
      recipient,
      complaint: complaint || null,
      title,
      createdAt: { $gte: windowTime },
    }).lean();

    if (existing) {
      return existing;
    }
  } catch (err) {
    // Continue if find fails
  }

  const created = await InAppNotification.create({
    recipient,
    complaint,
    title,
    message,
    link,
    read: false,
  }).catch((err) => {
    // Safe failure for in-app alerts
    console.error('Failed to create in-app notification:', err.message);
  });

  return created;
}

export async function cleanupDuplicatesForUser(userId) {
  try {
    const list = await InAppNotification.find({ recipient: userId })
      .sort({ createdAt: -1 })
      .limit(100)
      .lean();

    const seen = new Set();
    const idsToDelete = [];

    for (const item of list) {
      // Group by complaint, title, message and a 15-minute time window
      const timeBucket = Math.floor(new Date(item.createdAt).getTime() / (15 * 60 * 1000));
      const key = `${item.complaint || ''}_${item.title}_${item.message}_${timeBucket}`;
      if (seen.has(key)) {
        idsToDelete.push(item._id);
      } else {
        seen.add(key);
      }
    }

    if (idsToDelete.length > 0) {
      await InAppNotification.deleteMany({ _id: { $in: idsToDelete } });
    }
  } catch (err) {
    console.error('Failed to cleanup duplicate notifications:', err.message);
  }
}

export async function syncPendingForManager(userId) {
  try {
    const user = await User.findById(userId).lean();
    if (!user) return;
    const isReviewer = user.roles?.includes('reviewer') || user.roles?.includes('admin') || /Thippeswamy/i.test(user.name);
    if (!isReviewer) return;

    // 1. Any complaint currently in D3_PENDING_APPROVAL
    const pendingD3 = await Complaint.find({ status: 'D3_PENDING_APPROVAL' }).lean();
    for (const c of pendingD3) {
      const activeReviewer = await ComplaintAssignment.findOne({ complaint: c._id, role: 'REVIEWER', active: true }).lean();
      const isTarget = activeReviewer ? String(activeReviewer.assignee) === String(userId) : isReviewer;
      if (isTarget) {
        const notifExists = await InAppNotification.findOne({
          recipient: userId,
          complaint: c._id,
          title: 'D3 Root Cause & CAPA Submitted for Approval',
        }).lean();
        if (!notifExists) {
          const frpUser = c.frp ? await User.findById(c.frp, { name: 1 }).lean() : null;
          await InAppNotification.create({
            recipient: userId,
            complaint: c._id,
            title: 'D3 Root Cause & CAPA Submitted for Approval',
            message: `${frpUser?.name || 'FRP'} submitted D3 root cause analysis and CAPA plan for complaint ${c.complaintNumber} for your review and approval.`,
            link: `/complaints/${c._id}?tab=D3`,
            read: false,
          });
        }
      }
    }

    // Clean up any stale bogus SLA extension notices generated by schema defaults
    await InAppNotification.deleteMany({ title: 'D2 SLA Extension Request', message: /No reason specified/ });

    // 2. Any complaint with pending D2 SLA Extension (must have genuine requestedAt timestamp)
    const pendingExt = await Complaint.find({
      'd2.slaExtension.status': 'PENDING',
      'd2.slaExtension.requestedAt': { $exists: true, $ne: null },
    }).lean();
    for (const c of pendingExt) {
      const notifExists = await InAppNotification.findOne({
        recipient: userId,
        complaint: c._id,
        title: 'D2 SLA Extension Request',
      }).lean();
      if (!notifExists) {
        const frpUser = c.frp ? await User.findById(c.frp, { name: 1 }).lean() : null;
        const ext = c.d2?.slaExtension;
        await InAppNotification.create({
          recipient: userId,
          complaint: c._id,
          title: 'D2 SLA Extension Request',
          message: `${frpUser?.name || 'FRP'} requested ${ext?.requestedHours || 24} hours extension for ${c.complaintNumber}: ${ext?.reason || 'No reason specified'}`,
          link: `/complaints/${c._id}?tab=D2`,
          read: false,
        });
      }
    }
  } catch (err) {
    // Non-blocking sync
  }
}

export async function listForUser(userId, limit = 20) {
  await syncPendingForManager(userId);
  await cleanupDuplicatesForUser(userId);
  const notifications = await InAppNotification.find({ recipient: userId })
    .sort({ createdAt: -1 })
    .limit(limit)
    .lean();
  const unreadCount = await InAppNotification.countDocuments({ recipient: userId, read: false });
  return { notifications, unreadCount };
}

export async function markAllRead(userId) {
  const now = new Date();
  await InAppNotification.updateMany(
    { recipient: userId, read: false },
    { $set: { read: true, readAt: now } }
  );
  return { success: true };
}

export async function markRead(notificationId, userId) {
  await InAppNotification.updateOne(
    { _id: notificationId, recipient: userId },
    { $set: { read: true, readAt: new Date() } }
  );
  return { success: true };
}
